int	count_comas(char *texture)
{
	int	i;
	int	count;

	i = 0;
	count = 0;
	while (texture[i])
	{
		if (texture[i] == ',')
			count++;
		i++;
	}
	if (count != 2)
		return (1);
	return (0);
}
